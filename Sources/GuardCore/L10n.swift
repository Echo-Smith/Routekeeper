import Foundation

public enum AppLanguage: String, CaseIterable, Sendable {
    case system, zhHans, en
    public var title: String {
        switch self {
        case .system: return L10n.t("lang.system")
        case .zhHans: return "简体中文"
        case .en: return "English"
        }
    }
}

public enum AppAppearance: String, CaseIterable, Sendable {
    case system, light, dark
    public var title: String {
        switch self {
        case .system: return L10n.t("appearance.system")
        case .light: return L10n.t("appearance.light")
        case .dark: return L10n.t("appearance.dark")
        }
    }
}

